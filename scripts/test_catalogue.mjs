import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
vm.runInNewContext(ts.transpileModule(readFileSync('src/lib/catalogue-types.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports});
const {catalogueRows,catalogueFreshness,catalogueCoverage}=exports;
const base={description:'Observed series',category:'Rates',frequency:'Daily',source:'FRED',kind:'Macro'};
const rows=[{...base,id:'b',name:'US 10Y Treasury Yield',technicalId:'DGS10',count:100},{...base,id:'a',name:'US 2Y Treasury Yield',technicalId:'DGS2',count:100},{...base,id:'c',name:'Micron',technicalId:'MU',count:200,kind:'Market',source:'Yahoo Finance'}];
const filters={query:'',kind:'',source:'',frequency:'',category:''};
assert.equal(catalogueRows(rows,{...filters,query:'dgs10'}).length,1);
assert.equal(catalogueRows(rows,{...filters,query:'treasury',kind:'Macro',source:'FRED',frequency:'Daily',category:'Rates'}).length,2);
assert.equal(catalogueRows(rows,{...filters,source:'SEC EDGAR'}).length,0);
assert.equal(catalogueRows(rows,filters,'count',false).map(r=>r.id).join(','),'c,a,b');
assert.equal(rows[0].id,'b');
assert.equal(catalogueRows(rows,{...filters,query:'rates'}).length,3,'Category is searchable');
const ranked=[{...rows[0],id:'technical',name:'Other',technicalId:'Treasury'},{...rows[0],id:'human',name:'Treasury',technicalId:'OTHER'}];
assert.equal(catalogueRows(ranked,{...filters,query:'Treasury'})[0].id,'human');
const stored={...rows[0],from:'1962-01-02',to:'2026-10-01',count:16173};
assert.equal(catalogueCoverage(stored),'1962 → 2026');
assert.equal(catalogueCoverage({...stored,from:'Unavailable'}),'Unavailable');
assert.equal(catalogueFreshness(stored,'2026-10-17').label,'16d old');
assert.equal(catalogueFreshness(stored,'2026-10-17').tone,'warning');
assert.equal(catalogueFreshness({...stored,kind:'Fundamental'},'2026-10-17').tone,'neutral');
assert.equal(catalogueFreshness({...stored,to:'bad'},'2026-10-17').label,'Unavailable');
assert.equal(catalogueFreshness({...stored,count:0},'2026-10-17').label,'Unavailable');
assert.equal(catalogueFreshness(stored,'2026-09-30').label,'Future-dated');
const component=readFileSync('src/components/data-catalogue.tsx','utf8');
for(const contract of ['aria-sort','tabIndex={0}','Technical details','catalogue-detail-rail','aria-pressed'])assert(component.includes(contract),contract);
for(const contract of ['Last ingestion','Latest filing','Observation date','Metadata updated','Clear filters','filtered.find'])assert(component.includes(contract),contract);
const data=readFileSync('src/lib/catalogue-data.ts','utf8');
assert(data.includes("'NaN'::float8,'Infinity'::float8,'-Infinity'::float8"));
assert(data.includes('valid_count'));assert(!data.includes('fetch('),'No external provider request per row');
const error=readFileSync('src/app/data/error.tsx','utf8');assert(error.includes('router.refresh()'));assert(!error.includes('error.message'));
const explorer=readFileSync('src/components/chart-explorer.tsx','utf8');
assert(!explorer.includes('volume-lane'),'Use one integrated volume lane');
assert(explorer.includes('DEFAULT_EQUITY_VIEW.indicators'));
if(process.env.FOCUS_TEST_URL){
 const response=await fetch(process.env.FOCUS_TEST_URL+'/data');assert.equal(response.status,200);const html=await response.text();
 for(const label of ['Data Catalogue','US 10Y Treasury Yield','SEC EDGAR','Yahoo Finance','KanzQuant Derived','Series Details','Technical details'])assert(html.includes(label),label);
 assert(!html.includes('>NaN'));assert(!html.includes('DEMO FEED'));
}
console.log('Catalogue search/filter/stable sort/no mutation, selection/keyboard/scroll contracts, real multi-source route and single integrated chart volume passed.');
